export const EXERCISES = entries.map(
  ([key, name, muscle, equipment, summary, steps, cues]) => ({
    key,
    name,
    muscle,
    equipment,
    summary,
    steps,
    cues,
    instructions: [...steps, ...cues].join("\n"),
  }),
);

export function searchExercises(
  query = "",
  muscle = "全部",
  equipment = "全部",
) {
  const term = String(query).trim().toLowerCase();
  return EXERCISES.filter(
    (item) =>
      (muscle === "全部" || item.muscle === muscle) &&
      (equipment === "全部" || item.equipment === equipment) &&
      (!term ||
        `${item.name} ${item.muscle} ${item.equipment} ${item.summary}`
          .toLowerCase()
          .includes(term)),
  );
}
